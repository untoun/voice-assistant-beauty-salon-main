def _get_now() -> datetime:
    """Текущее время с fallback."""
    if _ZONEINFO_AVAILABLE and _ZoneInfo is not None:
        try:
            tz = _ZoneInfo(settings.timezone)
            return datetime.now(tz)
        except Exception:
            pass
    return datetime.now()


def _build_working_days_list(today: date, days_ahead: int = 14) -> str:
    """Список ближайших рабочих дней с точными датами."""
    weekdays_ru = [
        "понедельник", "вторник", "среда", "четверг",
        "пятница", "суббота", "воскресенье",
    ]
    months_ru = [
        "января", "февраля", "марта", "апреля", "мая", "июня",
        "июля", "августа", "сентября", "октября", "ноября", "декабря",
    ]

    lines = []
    current = today
    for _ in range(days_ahead):
        wd = weekdays_ru[current.weekday()]
        month = months_ru[current.month - 1]
        iso = current.strftime("%Y-%m-%d")
        if current.weekday() in WORKING_WEEKDAYS:
            lines.append(
                f"  ✅ {current.day} {month} ({wd}) → {iso}"
            )
        else:
            lines.append(
                f"  ❌ {current.day} {month} ({wd}) — ВЫХОДНОЙ"
            )
        current += timedelta(days=1)

    return "\n".join(lines)


def get_system_prompt(services_list: str | None = None) -> str:
    """Генерация системного промпта с актуальными данными."""
    now = _get_now()
    today = now.date()
    tomorrow = today + timedelta(days=1)
    day_after = today + timedelta(days=2)

    weekdays_ru = [
        "понедельник", "вторник", "среда", "четверг",
        "пятница", "суббота", "воскресенье",
    ]
    months_ru = [
        "января", "февраля", "марта", "апреля", "мая", "июня",
        "июля", "августа", "сентября", "октября", "ноября", "декабря",
    ]

    def fmt_date(d: date) -> str:
        return (
            f"{d.day} {months_ru[d.month - 1]} "
            f"({weekdays_ru[d.weekday()]}), {d.strftime('%Y-%m-%d')}"
        )

    working_days_list = _build_working_days_list(today, days_ahead=14)

    return SYSTEM_PROMPT_TEMPLATE.format(
        salon_name=settings.salon_name,
        services_list=services_list or SERVICES_DEFAULT,
        current_date=fmt_date(today),
        current_weekday=weekdays_ru[now.weekday()],
        tomorrow=fmt_date(tomorrow),
        day_after_tomorrow=fmt_date(day_after),
        working_hours_start=settings.working_hours_start,
        working_hours_end=settings.working_hours_end,
        working_days_list=working_days_list,
    )